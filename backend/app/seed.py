def seed() -> None:
    """既存データを削除した上で担当者と車両を投入する。"""
    Base.metadata.create_all(engine)
    now = now_iso()

    with SessionLocal() as db:
        # イベント → 車両 → 担当者 の順で消す（外部キーの依存順）
        db.query(VehicleEvent).delete()
        db.query(Vehicle).delete()
        db.query(User).delete()

        for name, role in USERS:
            db.add(User(name=name, role=role, active=True, created_at=now))

        for row in VEHICLES:
            (
                vehicle_no, maker, model, model_year, mileage_km, color,
                displacement, price_yen, shaken_expires_on, repair_history,
                location, remark,
            ) = row
            db.add(
                Vehicle(
                    vehicle_no=vehicle_no,
                    maker=maker,
                    model=model,
                    model_year=model_year,
                    mileage_km=mileage_km,
                    color=color,
                    displacement=displacement,
                    price_yen=price_yen,
                    shaken_expires_on=shaken_expires_on,
                    repair_history=repair_history,
                    location=location,
                    remark=remark,
                    status="IN_STOCK",
                    version=1,
                    created_at=now,
                    updated_at=now,
                )
            )
        db.commit()
        print(f"担当者 {len(USERS)}名、車両 {len(VEHICLES)}台を投入しました。")


if __name__ == "__main__":
    seed()
